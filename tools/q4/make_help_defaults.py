#!/usr/bin/env python3
"""Writes core/interface/q4/q4HelpDefaults.inc from sd-card/Q4Control.json,
so the help texts built into the firmware are the same as the sample JSON.

    python3 tools/q4/make_help_defaults.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "sd-card", "Q4Control.json")
DST = os.path.join(ROOT, "core", "interface", "q4", "q4HelpDefaults.inc")
PAGES = ["material", "granular", "filter", "color", "space", "mod", "commands", "about", "credit"]
MAX_LINES = 32
MAX_LINE = 239
MAX_CREDIT_LINES = 8
MAX_CREDIT_LINE = 31


def c_string(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ord(ch) < 0x80:
            out.append(ch)
        else:
            out.append("".join("\\x%02X\" \"" % b for b in ch.encode("utf-8")))
    return '"' + "".join(out) + '"'


def main():
    with open(SRC, encoding="utf-8") as f:
        help_ = json.load(f)["help"]
    lines = ["// Generated by tools/q4/make_help_defaults.py from sd-card/Q4Control.json. Do not edit.", ""]
    lines.append("constexpr const char* kHelpTitles[q4HelpCount] = {")
    for page in PAGES:
        lines.append("    %s," % c_string(help_[page]["title"]))
    lines.append("};")
    lines.append("")
    lines.append("constexpr const char* kHelpLines[q4HelpCount - 1][Q4Config::kHelpLines + 1] = {")
    for page in PAGES[:-1]:
        body = help_[page]["lines"]
        if len(body) > MAX_LINES:
            raise SystemExit("%s: %d lines (max %d)" % (page, len(body), MAX_LINES))
        for line in body:
            if len(line.encode("utf-8")) > MAX_LINE:
                raise SystemExit("%s: line too long (%d > %d): %s" % (page, len(line), MAX_LINE, line))
        lines.append("    {")
        for line in body:
            lines.append("        %s," % c_string(line))
        lines.append("        nullptr,")
        lines.append("    },")
    lines.append("};")
    lines.append("")
    credit = help_["credit"]
    if len(credit["lines"]) > MAX_CREDIT_LINES:
        raise SystemExit("credit: too many lines")
    lines.append("constexpr const char* kCreditLines[Q4Config::kCreditLines + 1] = {")
    for line in credit["lines"]:
        if len(line.encode("utf-8")) > MAX_CREDIT_LINE:
            raise SystemExit("credit: line too long: %s" % line)
        lines.append("    %s," % c_string(line))
    lines.append("    nullptr,")
    lines.append("};")
    lines.append("constexpr const char* kCopyright = %s;" % c_string(credit["copyright"]))
    with open(DST, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("Wrote %s" % os.path.relpath(DST, ROOT))


if __name__ == "__main__":
    main()
